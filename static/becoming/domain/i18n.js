export function topicLabel(topic='random'){
  const normalized=String(topic||'random').toLowerCase().trim().replaceAll('&','and').replace(/[^a-z0-9]+/g,'_').replace(/^_|_$/g,'');
  const key=`practice.topic.${normalized||'random'}`;
  const translated=t(key);
  return translated===key?String(topic||''):translated;
}


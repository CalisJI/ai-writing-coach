export function createSpeakingController({session,recorder=createLocalAudioRecorder(),transcribe=api.transcribeSpeech,pronunciationAssess=api.assessPronunciation,onChange=()=>{}}={}){
  const payload=session?.payload||null;
  const segments=payload?.transcript?.segments||[];
  const ids=segments.map(segment=>segment.segment_id);
  const initial=ids.includes(session?.selected_segment_id)?session.selected_segment_id:ids[0]||null;
  const model={
    selected:initial,
    playbackRate:1,
    readText:false,
    attempts:Object.fromEntries(ids.map(id=>[id,0])),
    asrStatus:'idle',
    asrTranscript:'',
    asrWords:[],
    asrError:'',
    asrErrorMessage:'',
    evaluation:null,
    pronunciationStatus:'idle',
    pronunciation:null,
    pronunciationError:'',
    pronunciationErrorMessage:'',
  };
  let pronunciationGeneration=0;
  const changed=()=>onChange({...model});

  return {
    model,
    recorder,
    html(){
      const c=copy();
      const a=asrCopy();
      const segment=segments.find(item=>item.segment_id===model.selected);
      const index=segments.findIndex(item=>item.segment_id===model.selected);
      const recording=recorder.snapshot();
      const meaning=translationFor(payload,model.selected);
      const level=levelChip();
      const promptMs=segment?Math.max(0,Number(segment.end_ms||0)-Number(segment.start_ms||0)):0;
      const isRecording=recording.status==='recording';
      const statusText=isRecording?c.recording
        :recording.status==='ready'?c.takeReady
        :recording.error==='microphone_unavailable'?c.micError
        :recording.error==='recording_empty'||recording.error==='recording_failed'?c.emptyRecording
        :recording.status==='unsupported'?c.unsupported:c.idle;

      const transcriptBody=model.asrStatus==='loading'
        ? `<p class="o-transcript-status" role="status">${esc(a.busy)}</p>`
        : model.asrTranscript
          ? `<div class="o-transcript-lines">${model.asrTranscript
              .split(/(?<=[.!?。！？])\s+/)
              .filter(Boolean)
              .map(line=>`<p>${transcriptTokenMarkup(line)}</p>`)
              .join('')}</div>`
          : model.asrError
            ? `<p class="o-transcript-status o-transcript-status--warn" role="alert">${esc(model.asrErrorMessage||a.failed)}</p>`
            : `<p class="o-transcript-status">${esc(c.transcriptEmpty)}</p>`;

      return `<section class="o-page speaking-page" data-speaking-core>
        <div class="o-speak">
          <div class="o-speak-main">

            <section class="o-card o-exercise">
              <div class="o-exercise-kicker">
                <span class="o-label">${esc(c.exercise)}</span>
                <button type="button" class="o-btn o-btn--ghost o-btn--compact" data-speaking-back-listening>${oIcon('arrowLeft')}<span>${esc(c.backListening)}</span></button>
              </div>
              <h2 class="o-exercise-prompt">${segment?esc(segment.original_text):''}</h2>
              <div class="o-exercise-meta">
                ${level?`<span class="o-band-chip">${esc(level.code)}</span><span class="o-meta-item">${esc(level.label)}</span>`:''}
                <span class="o-meta-item">${oIcon('clock')}<span>${stamp(promptMs)}</span></span>
                <button type="button" class="o-btn o-btn--outline o-btn--compact o-exercise-rubric" data-speaking-rubric>${oIcon('rubric')}<span>${esc(c.viewRubric)}</span></button>
              </div>
            </section>

            <h3 class="o-speak-heading">${esc(c.reference)}</h3>
            <div class="o-ref-head">
              <span class="o-ref-lead">${oIcon('volume')}<span>${esc(c.listenPrompt)}</span></span>
              <span class="o-ref-nav">
                <button type="button" class="o-icon-button" data-speaking-previous ${index<=0?'disabled':''} aria-label="${esc(matchCopy().previous)}">${oIcon('chevronDown')}</button>
                <span class="o-ref-count">${esc(c.segmentOf.replace('{n}',String(index+1)).replace('{total}',String(segments.length)))}</span>
                <button type="button" class="o-icon-button" data-speaking-next ${index<0||index>=segments.length-1?'disabled':''} aria-label="${esc(matchCopy().next)}">${oIcon('chevronUp')}</button>
              </span>
              <button type="button" class="o-btn o-btn--outline o-btn--compact" data-speaking-read-text aria-pressed="${model.readText}">${oIcon('read')}<span>${esc(c.readText)}</span></button>
            </div>

            <section class="o-card o-ref-card">
              <!-- The prompt is a segment of the lesson video, so the player
                   has to be on the page for the play control to reach it. -->
              <div class="o-ref-frame">${mediaPlayer(payload.playback,payload.asset?.title)}</div>
              <button type="button" class="o-round-button" data-speaking-replay aria-label="${esc(c.replay)}">${oIcon('play')}</button>
              <div class="o-ref-meta">
                <strong>${esc(c.promptAudio)}</strong>
                <span>${stamp(promptMs)}</span>
              </div>
              <label class="o-ref-rate">
                <span class="o-visually-hidden">${esc(c.speed)}</span>
                <select data-speaking-rate aria-label="${esc(c.speed)}">
                  ${[.75,1,1.25].map(rate=>`<option value="${rate}" ${rate===model.playbackRate?'selected':''}>${rate.toFixed(2).replace(/0$/,'')}x</option>`).join('')}
                </select>
              </label>
            </section>

            ${model.readText&&segment?`<div class="o-ref-text">
              <p class="o-ref-source" aria-label="${esc(segment.original_text)}">${transcriptTokenMarkup(segment.original_text)}</p>
              ${meaning?`<p class="o-ref-meaning"><b>${esc(c.meaning)}</b> ${esc(meaning)}</p>`:''}
            </div>`:''}

            <h3 class="o-speak-heading">${esc(c.recordHeading)}</h3>
            <section class="o-card o-recorder ${isRecording?'is-recording':''}">
              <div class="o-rec-row">
                <div class="o-rec-state">
                  <strong data-rec-status>${esc(statusText)}</strong>
                  <span class="o-rec-clock"><span data-rec-elapsed>0:00</span> / ${stamp(MAX_RECORDING_MS)}</span>
                </div>
                <!-- Ticks, not a waveform. Nothing here measures loudness, so
                     the bars are a fixed ruler and the fill is elapsed time. -->
                <div class="o-rec-meter" aria-hidden="true"><span class="o-rec-meter-fill" data-rec-fill></span></div>
                ${isRecording
                  ? `<button type="button" class="o-rec-button is-recording" data-speaking-stop aria-label="${esc(c.stop)}">${oIcon('square')}</button>`
                  : `<button type="button" class="o-rec-button" data-speaking-record ${recording.supported?'':'disabled'} aria-label="${esc(c.record)}">${oIcon('speak')}</button>`}
              </div>

              <div class="o-rec-divider"></div>

              <div class="o-rec-playback">
                <strong>${esc(c.playback)}</strong>
                ${recording.url
                  ? `<audio controls preload="metadata" class="o-audio" src="${esc(recording.url)}"></audio>`
                  : `<span class="o-rec-playback-empty">${esc(c.ready)}</span>`}
              </div>

              <div class="o-rec-divider"></div>

              <div class="o-rec-transcript" data-speaking-asr-result>
                <div class="o-rec-transcript-head">
                  <strong>${esc(c.transcript)}</strong>
                  <span class="o-chip">${esc(c.autoGenerated)}</span>
                </div>
                ${transcriptBody}
                ${sourceCheck(model)}
              </div>
            </section>

            <div class="o-speak-actions">
              <button type="button" class="o-btn o-btn--outline" data-speaking-discard ${recording.url?'':'disabled'}>${oIcon('undo')}<span>${esc(c.discard)}</span></button>
              <a class="o-btn o-btn--outline ${recording.url?'':'is-disabled'}" data-speaking-download ${recording.url?`href="${esc(recording.url)}" download="orena-speaking-take.webm"`:'aria-disabled="true"'}>${oIcon('download')}<span>${esc(c.download)}</span></a>
              <button type="button" class="o-btn o-btn--primary o-speak-feedback" data-speaking-pronunciation-action ${recording.blob&&model.pronunciationStatus!=='loading'?'':'disabled'}>
                <span>${esc(c.seeFeedback)}</span>${oIcon('arrowRight')}
              </button>
            </div>

            <p class="o-speak-privacy">${esc(matchCopy().privacy)}</p>
          </div>

          ${feedbackRail(model)}
        </div>
      </section>`;
    },
    select(segmentId){
      if(!ids.includes(segmentId))return false;
      if(recorder.snapshot().status==='recording')return false;
      recorder.discard();
      pronunciationGeneration++;
      model.pronunciationStatus='idle';
      model.pronunciation=null;
      model.pronunciationError='';
      model.pronunciationErrorMessage='';
      model.selected=segmentId;
      model.asrStatus='idle';
      model.asrTranscript='';
      model.asrWords=[];
      model.asrError='';
      model.evaluation=null;
      selectSharedMediaSegment(session.learning_language,segmentId);
      changed();
      return true;
    },
    selectRelative(offset){
      const index=ids.indexOf(model.selected);
      const target=ids[index+offset];
      if(!target)return false;
      return this.select(target);
    },
    toggleReadText(){
      model.readText=!model.readText;
      changed();
      return model.readText;
    },
    async startRecording(){
      pronunciationGeneration++;
      model.pronunciationStatus='idle';
      model.pronunciation=null;
      model.pronunciationError='';
      model.pronunciationErrorMessage='';
      model.asrStatus='idle';
      model.asrTranscript='';
      model.asrWords=[];
      model.asrError='';
      model.evaluation=null;
      const started=await recorder.start();
      changed();
      return started;
    },
    async stopRecording(){
      const result=await recorder.stop();
      if(!result||!model.selected){
        changed();
        return false;
      }

      model.attempts[model.selected]=(model.attempts[model.selected]||0)+1;
      model.asrStatus='loading';
      model.asrTranscript='';
      model.asrWords=[];
      model.asrError='';
      model.evaluation=null;
      changed();

      try{
        const mime=result.mime_type||'audio/webm';
        const extension=mime.includes('ogg')?'ogg':mime.includes('mp4')?'m4a':'webm';
        const response=await transcribe(
          result.blob,
          session.learning_language,
          `speaking-take.${extension}`,
        );
        model.asrTranscript=typeof response?.text==='string'?response.text.trim():'';
        model.asrWords=Array.isArray(response?.words)?response.words:[];
        model.asrStatus='ready';
        if(model.asrTranscript){
          const selectedSegment=segments.find(item=>item.segment_id===model.selected);
          model.evaluation=evaluateSpeechTranscript(selectedSegment?.original_text||'',model.asrTranscript);
        }else{
          model.asrError='empty_transcript';
          model.evaluation=null;
        }
      }catch(error){
        model.asrStatus='error';
        model.asrError=error?.category||String(error?.status||'speech_asr_failed');
        model.asrErrorMessage=typeof error?.message==='string'?error.message:'';
      }
      changed();
      return true;
    },
    async assessPronunciation(){
      const recording=recorder.snapshot();
      const selectedSegment=segments.find(item=>item.segment_id===model.selected);
      if(!recording.blob||!selectedSegment||model.pronunciationStatus==='loading')return false;

      const generation=++pronunciationGeneration;
      model.pronunciationStatus='loading';
      model.pronunciation=null;
      model.pronunciationError='';
      model.pronunciationErrorMessage='';
      changed();

      const mime=recording.mime_type||'audio/webm';
      const extension=mime.includes('ogg')?'ogg':mime.includes('mp4')?'m4a':'webm';
      try{
        const response=await pronunciationAssess(
          recording.blob,
          session.learning_language,
          selectedSegment.original_text||'',
          `speaking-take.${extension}`,
        );
        if(generation!==pronunciationGeneration)return false;
        model.pronunciation=response;
        model.pronunciationStatus='ready';
      }catch(error){
        if(generation!==pronunciationGeneration)return false;
        model.pronunciationStatus=error?.category==='pronunciation_unconfigured'?'unavailable':'error';
        model.pronunciationError=error?.category||String(error?.status||'pronunciation_failed');
        model.pronunciationErrorMessage=typeof error?.message==='string'?error.message:'';
      }
      changed();
      return model.pronunciationStatus==='ready';
    },
    discardRecording(){
      const discarded=recorder.discard();
      if(discarded){
        pronunciationGeneration++;
        model.pronunciationStatus='idle';
        model.pronunciation=null;
        model.pronunciationError='';
        model.pronunciationErrorMessage='';
        model.asrStatus='idle';
        model.asrTranscript='';
        model.asrWords=[];
        model.asrError='';
        model.evaluation=null;
        changed();
      }
      return discarded;
    },
    setPlaybackRate(value){
      if(![.75,1,1.25].includes(value))return false;
      model.playbackRate=value;
      return true;
    },
    cleanup(){recorder.cleanup();},
  };
}


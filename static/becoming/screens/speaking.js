export async function renderSpeaking(root,{recorderFactory=createLocalAudioRecorder}={}){
  const session=getSharedMediaSession(state.language);
  if(!session){
    root.innerHTML=emptyPage();
    root.querySelector('[data-speaking-open-listening]')?.addEventListener('click',()=>go('listen'));
    root.querySelectorAll('[data-speaking-lesson]').forEach(button=>{
      button.addEventListener('click',()=>{
        // Ask Listening to prepare this exact lesson, then go there. Listening
        // builds the session Speaking needs; the learner does not have to.
        requestLessonAutostart(state.language,button.dataset.speakingLesson||'');
        go('listen');
      });
    });
    return null;
  }

  let mounted=false;
  let disposed=false;
  let controller;
  let ticker=null;

  /* The clock and the fill are the only things that change while a take runs,
     so they are written straight to their nodes. Re-rendering the screen every
     second would tear down the audio element and the transcript with it. */
  const stopTicker=()=>{
    if(ticker){clearInterval(ticker);ticker=null;}
  };
  const startTicker=()=>{
    stopTicker();
    if(disposed)return;
    const startedAt=Date.now();
    ticker=setInterval(()=>{
      const elapsed=Date.now()-startedAt;
      const clock=root.querySelector('[data-rec-elapsed]');
      const fill=root.querySelector('[data-rec-fill]');
      if(!clock||!fill){stopTicker();return;}
      clock.textContent=stamp(Math.min(elapsed,MAX_RECORDING_MS));
      fill.style.width=`${Math.min(100,(elapsed/MAX_RECORDING_MS)*100)}%`;
      if(elapsed>=MAX_RECORDING_MS){
        stopTicker();
        controller.stopRecording();
      }
    },200);
  };

  const render=()=>{
    /* Recording starts behind a permission prompt, which the learner can leave
       sitting while they walk to another screen. The controller keeps running
       and calls back here, and the node test alone cannot tell this view's
       markup from its replacement's - so the view says outright whether it is
       still the one on the page. */
    if(disposed)return;
    if(mounted&&!root.querySelector('[data-speaking-core]'))return;
    root.innerHTML=controller.html();
    mounted=true;

    root.querySelector('[data-speaking-back-listening]')?.addEventListener('click',()=>go('listen'));
    root.querySelector('[data-speaking-rubric]')?.addEventListener('click',showRubric);
    root.querySelector('[data-speaking-read-text]')?.addEventListener('click',()=>controller.toggleReadText());
    root.querySelector('[data-speaking-previous]')?.addEventListener('click',()=>controller.selectRelative(-1));
    root.querySelector('[data-speaking-next]')?.addEventListener('click',()=>controller.selectRelative(1));
    root.querySelector('[data-speaking-record]')?.addEventListener('click',async()=>{
      const started=await controller.startRecording();
      if(started&&!disposed)startTicker();
    });
    root.querySelector('[data-speaking-stop]')?.addEventListener('click',()=>{
      stopTicker();
      controller.stopRecording();
    });
    root.querySelector('[data-speaking-discard]')?.addEventListener('click',()=>controller.discardRecording());
    root.querySelector('[data-speaking-pronunciation-action]')?.addEventListener('click',()=>controller.assessPronunciation());
    root.querySelector('[data-speaking-replay]')?.addEventListener('click',()=>{
      const segment=session.payload.transcript.segments.find(item=>item.segment_id===controller.model.selected);
      if(segment)replaySegment(root,session.payload.playback,segment.start_ms,segment.end_ms,controller.model.playbackRate);
    });
    root.querySelector('[data-speaking-rate]')?.addEventListener('change',event=>{
      const rate=Number(event.target.value);
      if(setMediaPlaybackRate(root,session.payload.playback,rate))controller.setPlaybackRate(rate);
      else event.target.value=String(controller.model.playbackRate);
    });
    if(controller.model.playbackRate!==1){
      root.querySelector('#listeningPlayer')?.addEventListener('load',()=>setMediaPlaybackRate(root,session.payload.playback,controller.model.playbackRate),{once:true});
    }
  };

  controller=createSpeakingController({session,recorder:recorderFactory(),onChange:render});
  root._cleanupScreen=()=>{disposed=true;stopTicker();controller.cleanup();};
  render();
  return controller;
}

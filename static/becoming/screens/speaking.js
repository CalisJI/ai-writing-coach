/* The learner's own target band, the one they set for Writing. The reference
   prints a CEFR chip next to the exercise; this is the only band the product
   actually holds, so it is that one rather than a level invented per line. */
const BAND_KEYS={
  A1:'beginner',A2:'elementary',B1:'intermediate',B2:'upper',C1:'advanced',C2:'proficient',
  HSK1:'beginner',HSK2:'elementary',HSK3:'intermediate',HSK4:'upper',HSK5:'advanced',HSK6:'proficient',
};
function levelChip(){
  const level=String(state.draft?.level||'').toUpperCase();
  const key=BAND_KEYS[level];
  return key?{code:level,label:t(`band.${key}`)}:null;
}

function scoreBand(value){
  if(!Number.isFinite(value))return null;
  if(value>=90)return 'excellent';
  if(value>=75)return 'good';
  if(value>=60)return 'fair';
  return 'weak';
}

/* A ring, or the space one would take. r=19 on a 44 box gives a 119.4
   circumference, which the arc length is a straight percentage of. */
const RING_LENGTH=2*Math.PI*19;
function ring(value){
  const band=scoreBand(value);
  if(!band){
    return `<span class="o-ring o-ring--pending" aria-hidden="true">&mdash;</span>`;
  }
  const arc=(Math.max(0,Math.min(100,value))/100)*RING_LENGTH;
  return `<span class="o-ring o-ring--${band}">
    <svg viewBox="0 0 44 44" aria-hidden="true">
      <circle class="o-ring-track" cx="22" cy="22" r="19"/>
      <circle class="o-ring-arc" cx="22" cy="22" r="19" stroke-dasharray="${arc.toFixed(1)} ${RING_LENGTH.toFixed(1)}"/>
    </svg>
    <b>${Math.round(value)}</b>
  </span>`;
}

function metric(label,value,note,info,attributes=''){
  const f=feedbackCopy();
  const band=scoreBand(value);
  return `<div class="o-metric"${attributes?` ${attributes}`:''}>
    <div class="o-metric-head">
      <strong>${esc(label)}</strong>
      <span class="o-metric-info" title="${esc(info)}" aria-label="${esc(info)}" role="img">${oIcon('info')}</span>
    </div>
    <div class="o-metric-body">
      ${ring(value)}
      <span class="o-metric-band">${esc(band?f[band]:f.pending)}</span>
    </div>
    ${note?`<p class="o-metric-note">${esc(note)}</p>`:''}
  </div>`;
}

function bandNote(prefix,value){
  const f=feedbackCopy();
  const band=scoreBand(value);
  return band?f[`${prefix}${band[0].toUpperCase()}${band.slice(1)}`]:'';
}

/* Highlights and next steps are read off the two results, not written for the
   screenshot: an item appears only when a number or a token list supports it. */
function feedbackLists(model){
  const f=feedbackCopy();
  const pron=model.pronunciation;
  const evaluation=model.evaluation;
  const highlights=[];
  const steps=[];

  if(typeof pron?.accuracy_score==='number'&&pron.accuracy_score>=85)highlights.push(f.hlClear);
  if(typeof pron?.completeness_score==='number'&&pron.completeness_score>=90)highlights.push(f.hlComplete);
  if(typeof pron?.fluency_score==='number'&&pron.fluency_score>=80)highlights.push(f.hlPace);
  if(typeof evaluation?.content_match==='number'&&evaluation.content_match>=85)highlights.push(f.hlOnTopic);

  const weakWords=(Array.isArray(pron?.words)?pron.words:[])
    .filter(word=>(typeof word.accuracy_score==='number'&&word.accuracy_score<80)
      ||String(word.error_type||'None').toLowerCase()!=='none')
    .map(word=>word.word)
    .filter(Boolean)
    .slice(0,4);
  if(weakWords.length)steps.push(f.nsWords.replace('{words}',weakWords.join(', ')));
  if(evaluation?.missing_tokens?.length)steps.push(f.nsMissing.replace('{words}',evaluation.missing_tokens.slice(0,5).join(', ')));
  if(typeof pron?.fluency_score==='number'&&pron.fluency_score<80)steps.push(f.nsFlow);
  if(typeof pron?.completeness_score==='number'&&pron.completeness_score<90)steps.push(f.nsComplete);

  return {highlights,steps,weakWords};
}

